export const permissionScopes = (role, permission) =>
  ROLE_PERMISSION_MATRIX[String(role || '').trim().toUpperCase()]?.[permission] || [];

export const hasPermission = (role, permission, requiredScope = null) => {
  const scopes = permissionScopes(role, permission);
  return scopes.length > 0 && (!requiredScope || scopes.includes(requiredScope));
};

export const permissionsForRole = (role) =>
  Object.keys(ROLE_PERMISSION_MATRIX[String(role || '').trim().toUpperCase()] || {});
